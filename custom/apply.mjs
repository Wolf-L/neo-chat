#!/usr/bin/env node
// Applies the fork's customizations on top of a pristine upstream checkout.
// Run from the repository root before typecheck/test/build:
//   node custom/apply.mjs
// Upstream files stay untouched in git; this only rewrites the working tree.
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const CUSTOM_DIR = dirname(fileURLToPath(import.meta.url));

// Upstream files the overlay is allowed to replace. Every other overlay file
// must be new, so an upstream file with the same name fails the build instead
// of being silently overwritten.
export const OVERRIDES = ["src/lib/sync/scheduler.ts"];

// Upstream must still start sync through this module; otherwise the
// overridden scheduler would never run.
export const WIRING = {
  module: "@/lib/sync/scheduler",
  symbol: "startEncryptedSyncScheduler",
};

export const GENERATED_ROUTE = "src/app/api/sync/custom-preset/route.ts";
const GENERATED_ROUTE_SOURCE = `// Generated by custom/apply.mjs. Do not edit.
import { GET as getCustomSyncPreset } from "@/lib/sync/customServerPreset";

export async function GET() {
  return getCustomSyncPreset();
}
`;

function toPosix(path) {
  return path.replaceAll("\\", "/");
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}

/** Strips comments and trailing commas from JSONC without touching strings. */
export function parseJsonc(source) {
  let output = "";
  let index = 0;
  while (index < source.length) {
    const char = source[index];
    const next = source[index + 1];
    if (char === '"') {
      let end = index + 1;
      while (end < source.length && source[end] !== '"') {
        end += source[end] === "\\" ? 2 : 1;
      }
      output += source.slice(index, end + 1);
      index = end + 1;
    } else if (char === "/" && next === "/") {
      while (index < source.length && source[index] !== "\n") index += 1;
    } else if (char === "/" && next === "*") {
      const end = source.indexOf("*/", index + 2);
      index = end === -1 ? source.length : end + 2;
    } else if (char === ",") {
      let lookahead = index + 1;
      while (/\s/u.test(source[lookahead] ?? "")) lookahead += 1;
      if (source[lookahead] !== "}" && source[lookahead] !== "]") {
        output += char;
      }
      index += 1;
    } else {
      output += char;
      index += 1;
    }
  }
  return JSON.parse(output);
}

/** Lists overlay files and fails when upstream collides with one. */
export function planOverlay(root) {
  const overlayDir = join(CUSTOM_DIR, "overlay");
  return listFiles(overlayDir).map((source) => {
    const path = toPosix(relative(overlayDir, source));
    const target = join(root, path);
    if (existsSync(target) && !OVERRIDES.includes(path)) {
      throw new Error(
        `Upstream now ships ${path}; rename the overlay file or add it to OVERRIDES.`,
      );
    }
    if (!existsSync(target) && OVERRIDES.includes(path)) {
      throw new Error(
        `Upstream no longer ships ${path}; the override would never be used.`,
      );
    }
    return { path, source, target };
  });
}

export function copyOverlay(root) {
  return planOverlay(root).map(({ path, source, target }) => {
    mkdirSync(dirname(target), { recursive: true });
    cpSync(source, target);
    return path;
  });
}

export function writeGeneratedRoute(root) {
  const target = join(root, GENERATED_ROUTE);
  if (existsSync(target)) {
    throw new Error(`Upstream now ships ${GENERATED_ROUTE}.`);
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, GENERATED_ROUTE_SOURCE);
}

function isTestFile(path) {
  return /(?:^|\/)__tests__\/|\.test\.tsx?$/u.test(path);
}

function importsModule(source, module) {
  const quoted = module.replace(/[.*+?^${}()|[\]\\/]/gu, "\\$&");
  return new RegExp(`from\\s+["']${quoted}["']`, "u").test(source);
}

export function verifyWiring(root) {
  const users = listFiles(join(root, "src"))
    .map((path) => toPosix(relative(root, path)))
    .filter((path) => /\.tsx?$/u.test(path) && !isTestFile(path))
    .filter((path) => !OVERRIDES.includes(path))
    .filter((path) => {
      const source = readFileSync(join(root, path), "utf8");
      return (
        importsModule(source, WIRING.module) && source.includes(WIRING.symbol)
      );
    });
  if (!users.length) {
    throw new Error(
      `No upstream code imports ${WIRING.symbol} from ${WIRING.module} any more.`,
    );
  }
  return users;
}

/** Drops upstream tests of modules the overlay replaces. */
export function removeOverriddenTests(root) {
  const modules = OVERRIDES.map(
    (path) => `@/${path.replace(/^src\//u, "").replace(/\.tsx?$/u, "")}`,
  );
  const removed = [];
  for (const file of listFiles(join(root, "src"))) {
    const path = toPosix(relative(root, file));
    if (!isTestFile(path)) continue;
    const source = readFileSync(file, "utf8");
    if (modules.some((module) => importsModule(source, module))) {
      rmSync(file);
      removed.push(path);
    }
  }
  return removed;
}

export function mergeWranglerConfig(root) {
  const configPath = join(root, "wrangler.jsonc");
  const config = parseJsonc(readFileSync(configPath, "utf8"));
  const overrides = JSON.parse(
    readFileSync(join(CUSTOM_DIR, "wrangler.overrides.json"), "utf8"),
  );
  writeFileSync(
    configPath,
    `${JSON.stringify({ ...config, ...overrides }, null, 2)}\n`,
  );
  return Object.keys(overrides);
}

export function applyCustomizations(root) {
  const copied = copyOverlay(root);
  writeGeneratedRoute(root);
  const wiredBy = verifyWiring(root);
  const removedTests = removeOverriddenTests(root);
  const wranglerKeys = mergeWranglerConfig(root);
  return { copied, wiredBy, removedTests, wranglerKeys };
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const result = applyCustomizations(process.cwd());
  console.log(JSON.stringify(result, null, 2));
}
